#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Укорачивает слишком длинные промежутки между словами.

автор 20.09.2026: «иногда он делает слишком большие промежутки между
словами, что для профессионального чтеца неприемлемо».

Паузы делим на два рода:
  • внутри фразы — всё, что короче ГРАНИЦА_ФРАЗЫ; режем до ВНУТРИ;
  • между предложениями — длинные; режем до МЕЖДУ (их оставляем
    заметными, иначе новости слипнутся в кашу).
Режем с коротким сведением на стыке, иначе слышны щелчки.

Usage: obrezat-pauzy.py вход.wav выход.wav [внутри_мс] [между_мс]
"""
import sys
import numpy as np
import soundfile as sf

ГРАНИЦА_ФРАЗЫ = 0.70      # с — длиннее считаем концом предложения
СВЕДЕНИЕ = 0.006          # с — сглаживание стыка


def обрезать(путь_вх, путь_вых, внутри=0.20, между=0.45):
    x, sr = sf.read(путь_вх)
    if x.ndim > 1:
        x = x.mean(1)
    шаг = int(sr * 0.01)
    гр = np.array([np.sqrt((x[i:i + шаг] ** 2).mean() + 1e-12)
                   for i in range(0, len(x) - шаг, шаг)])
    порог = np.percentile(гр, 90) * 0.06
    тихо = гр < порог

    куски, срезано, i, прошл = [], 0.0, 0, 0
    while i < len(тихо):
        if not тихо[i]:
            i += 1
            continue
        j = i
        while j < len(тихо) and тихо[j]:
            j += 1
        длина = (j - i) * 0.01
        нач, кон = i * шаг, j * шаг
        # паузы у самых краёв записи не трогаем
        if нач > шаг * 3 and кон < len(x) - шаг * 3:
            предел = между if длина >= ГРАНИЦА_ФРАЗЫ else внутри
            if длина > предел:
                куски.append(x[прошл:нач + int(sr * предел)])
                срезано += длина - предел
                прошл = кон
        i = j
    куски.append(x[прошл:])

    # склейка с коротким сведением, чтобы не щёлкало
    n = int(sr * СВЕДЕНИЕ)
    итог = куски[0]
    for к in куски[1:]:
        if len(итог) > n and len(к) > n:
            спад = np.linspace(1, 0, n)
            итог = np.concatenate([итог[:-n],
                                   итог[-n:] * спад + к[:n] * (1 - спад),
                                   к[n:]])
        else:
            итог = np.concatenate([итог, к])
    sf.write(путь_вых, итог, sr)
    return срезано, len(x) / sr, len(итог) / sr


if __name__ == "__main__":
    вх, вых = sys.argv[1], sys.argv[2]
    внутри = float(sys.argv[3]) / 1000 if len(sys.argv) > 3 else 0.20
    между = float(sys.argv[4]) / 1000 if len(sys.argv) > 4 else 0.45
    с, было, стало = обрезать(вх, вых, внутри, между)
    print(f"срезано {с:.2f} с тишины: было {было:.2f} с, стало {стало:.2f} с")
